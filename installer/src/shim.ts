/**
 * app.asar に差し込む shim。
 *
 * 中身は Vencord 公式インストーラと同じく patcher.js を require するだけ。
 * Discord 本体（_app.asar）のブートは Vencord の patcher が末尾で行うので、
 * 旧 VoiceCord の連鎖 shim のような順序の制約はない。
 */

/** このインストーラが書いた shim を見分けるマーカー */
export const SHIM_MARKER = "VencordExtended shim v1";

/** 旧 VoiceCord Manager の連鎖 shim のマーカー（置き換え対象の判定にだけ使う） */
export const LEGACY_CHAIN_MARKER = "VoiceCord chain shim v1";

/** Discord 本体と同じ app 名を名乗る必要がある */
export const SHIM_PACKAGE_JSON = '{"name":"discord","main":"index.js"}';

export function renderShimSource(patcher: string): string {
    // JSON.stringify で Windows のバックスラッシュを正しくエスケープする
    return `// ${SHIM_MARKER} ---- generated by the vencord-extended installer, do not edit ----\n`
        + `require(${JSON.stringify(patcher)});\n`;
}

/** このインストーラの shim なら require 先の patcher を返す。違えば null */
export function parseShimPatcher(source: string): string | null {
    if (!source.includes(SHIM_MARKER)) return null;
    const m = /require\(("(?:[^"\\]|\\.)*")\);/.exec(source);
    if (!m) return null;
    try {
        const value: unknown = JSON.parse(m[1]);
        return typeof value === "string" ? value : null;
    } catch {
        return null;
    }
}

/** 旧 VoiceCord の連鎖 shim なら連鎖リストを返す。違えば null */
export function parseLegacyChain(source: string): string[] | null {
    if (!source.includes(LEGACY_CHAIN_MARKER)) return null;
    const m = /var CHAIN = (\[[^\]]*\]);/.exec(source);
    if (!m) return null;
    try {
        const parsed: unknown = JSON.parse(m[1]);
        if (!Array.isArray(parsed) || !parsed.every(x => typeof x === "string")) return null;
        return parsed;
    } catch {
        return null;
    }
}
